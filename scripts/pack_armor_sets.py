#!/usr/bin/env python3
"""Compile generated clothing parts and authored pivots for all 30 outfits."""
from pathlib import Path
import json
import sys
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'assets/art/armor-expansion'
OUT=ROOT/'build/armor-sets'
OUT.mkdir(parents=True,exist_ok=True)
sets=json.loads((ART/'sets.json').read_text())
assert len(sets)==30 and sum(s['class']=='heavy' for s in sets[5:])==15
missing=[s['name'] for s in sets if not (ART/(s['slug']+'.png')).exists()]
if missing and '--allow-incomplete' not in sys.argv:raise SystemExit('Missing source art: '+', '.join(missing))

def array(name,typ,values):
    return 'static const '+typ+' '+name+'[]={\n'+',\n'.join(','.join(map(str,values[i:i+24])) for i in range(0,len(values),24))+'\n};\n'

def compile_sprite(im,name,size):
    alpha=im.getchannel('A').point(lambda a:255 if a>=96 else 0)
    box=alpha.getbbox()
    assert box, name
    im=im.crop(box);old=im.size;im.thumbnail(size,Image.Resampling.LANCZOS)
    scale=(im.width/old[0],im.height/old[1])
    im.putalpha(im.getchannel('A').point(lambda a:255 if a>=210 else (a//64)*64 if a>=64 else 0))
    rgb=im.copy();im=im.quantize(colors=128,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
    pal=im.getpalette('RGBA');pal += [0]*(1024-len(pal))
    palette=[pal[i]|pal[i+1]<<8|pal[i+2]<<16|pal[i+3]<<24 for i in range(0,1024,4)]
    raw=list(im.get_flattened_data());data=[];rows=[]
    for y in range(im.height):
        row=raw[y*im.width:(y+1)*im.width];vis=[x for x,p in enumerate(row) if palette[p]>>24]
        lo,hi=(min(vis),max(vis)+1) if vis else (0,0)
        rows.extend((len(data),lo,hi));data.extend(row[lo:hi])
    assert len(data)<65536
    code=array(name+'_pixels','uint8_t',data)+array(name+'_rows','uint16_t',rows)+array(name+'_pal','uint32_t',[hex(p)+'u' for p in palette])
    entry='{%d,%d,%d,%d,%s_pixels,%s_rows,%s_pal}'%(im.width,im.height,im.width//2,im.height,name,name,name)
    rgb.save(OUT/(name+'.png'))
    return code,entry,box,scale,rgb

landmarks={
 'cinder-scout':(332,116,320,475,165,216,473,182),
 'salt-runner':(333,130,320,465,190,211,460,188),
 'caravan-leather':(331,121,314,477,165,218,475,193),
 'quarry-jack':(326,130,313,455,141,222,470,196),
 'road-warden':(337,128,322,467,165,218,468,191),
}
metadata=['/* Generated by scripts/pack_armor_sets.py. */\n#ifndef DUST_ARMOR_SETS_DATA_H\n#define DUST_ARMOR_SETS_DATA_H\n',
 'typedef struct {const char *name;int family[4];int tier,faction,armor,weight,speed,stealth,weather,heavy,owner,coverage;} ArmorSetDef;\n',
 'static const ArmorSetDef armorSets[ARMOR_SETS]={\n']
for s in sets:
    metadata.append('{%s,{%s},%d,%s,%d,%d,%d,%d,%d,%d,%d,%d},\n'%(
        json.dumps(s['name']),','.join(map(str,s['family'])),s['tier'],s['faction'],s['armor'],s['weight'],s['speed'],s['stealth'],s['weather'],s['class']=='heavy',s.get('owner',-1),s['arm_coverage']))
metadata.append('};\n#endif\n')
(ROOT/'src/armor_sets_data.h').write_text(''.join(metadata))

code=['/* Generated by scripts/pack_armor_sets.py. */\n#ifndef DUST_ARMOR_ART_DATA_H\n#define DUST_ARMOR_ART_DATA_H\n#define ARMOR_ART_FIRST ART_COUNT\n']
entries=[];fits=[];armfits=[];budget=0
for i,s in enumerate(sets):
    source=ART/(s['slug']+'.png')
    if not source.exists():
        entries+=['{0}']*6;fits.append('{0}');armfits.append('{{0},{0}}');continue
    im=Image.open(source).convert('RGBA');cols=2;rows=2 if i<5 else 3;cw=im.width/cols;ch=im.height/rows
    local_arm=[]
    for part,size in enumerate(((40,58),(42,42),(20,52),(22,26),(18,30),(18,30))):
        if part>=4 and i<5:
            entries.append('{0}');local_arm.append('{0}');continue
        x=part%2;y=part//2
        region=im.crop((round(x*cw),round(y*ch),round((x+1)*cw),round((y+1)*ch)))
        fragment,entry,box,scale,packed=compile_sprite(region,f'armor_{i:02d}_{part}',size)
        code.append(fragment);entries.append(entry);budget+=len(fragment)
        if part==0:
            raw=s.get('landmarks',landmarks.get(s['slug']))
            if raw:
                pts=[(v-box[j%2])*scale[j%2] for j,v in enumerate(raw)]
            else:
                w,h=packed.size
                fit=s.get('fit_normalized',[.54,.10,.51,.69,.115,.31,.89,.265])
                pts=[v*(w if j%2==0 else h) for j,v in enumerate(fit)]
            fits.append('{'+','.join(f'{v:.5f}f' for v in pts)+'}')
        if part>=4:
            w,h=packed.size
            def center(v):
                y=min(h-1,round(h*v));a=packed.getchannel('A');xs=[x for x in range(w) if a.getpixel((x,y))>=128]
                return (min(xs)+max(xs)+1)/2 if xs else w/2
            local_arm.append('{%.5ff,%.5ff,%.5ff,%.5ff}'%(center(.20),h*.20,center(.86),h*.86))
    armfits.append('{'+','.join(local_arm)+'}')
code.append('static const ArtSprite armorSprites[ARMOR_SETS*6]={\n'+',\n'.join(entries)+'\n};\n')
code.append('static const TorsoFit armorTorsoFits[ARMOR_SETS]={\n'+',\n'.join(fits)+'\n};\n')
code.append('static const float armorHeadFits[ARMOR_SETS][2]={'+','.join('{%.5ff,%.5ff}'%tuple(s.get('head_fit',[0,0])) for s in sets)+'};\n')
code.append('typedef struct {float upper[4],lower[4];} ArmorArmFit;\nstatic const ArmorArmFit armorArmFits[ARMOR_SETS]={\n'+',\n'.join(armfits)+'\n};\n#endif\n')
(ROOT/'src/armor_art_data.h').write_text(''.join(code))
(OUT/'manifest.json').write_text(json.dumps({'sets':30,'complete':30-len(missing),'new_heavy_sets':15,'missing':missing,'generated_c_bytes':budget,'sources':[s['slug']+'.png' for s in sets]},indent=2)+'\n')
print(f'Compiled {30-len(missing)}/30 armor sets; 15 of the new 25 are heavy; C data {budget} bytes.')
