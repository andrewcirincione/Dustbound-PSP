def arr(name,typ,vals):
 return 'static const '+typ+' '+name+'[] = {\n'+',\n'.join(','.join(map(str,vals[i:i+24])) for i in range(0,len(vals),24))+'\n};\n'
def spans(im,palette=None):
 raw=list(im.getdata());data=[];rows=[]
 for y in range(im.height):
  row=raw[y*im.width:(y+1)*im.width];vis=[x for x,p in enumerate(row) if (palette[p]>>24 if palette else p)]
  lo,hi=(min(vis),max(vis)+1) if vis else (0,0);rows.extend((len(data),lo,hi));data.extend(row[lo:hi])
 assert len(data)<65536
 return data,rows
def calibrate(im,points):
 left,front,right=points;sl=(front[1]-left[1])/(front[0]-left[0]);sr=(right[1]-front[1])/(right[0]-front[0]);b=1/(sl-sr);a=.5-b*sl
 lo=min(0,a*im.width);hi=max(0,a*im.width)+b*im.height
 result=im.transform((im.width,math.ceil(hi-lo)),Image.Transform.AFFINE,(1,0,0,-a/b,1/b,lo/b),Image.Resampling.BICUBIC)
 return result,[(x,a*x+b*y-lo) for x,y in points],dict(input_slopes=[sl,sr],output_slopes=[a+b*sl,a+b*sr],shear=a,vertical_scale=b)
def shadow(im,ax,ay,front):
 out=Image.new('L',(im.width+im.height,im.height*2));pix=out.load();alpha=im.getchannel('A');src=alpha.load()
 for y in range(im.height):
  for x in range(im.width):
   if src[x,y]<192:continue
   ground=front-abs(x-ax)*.5;z=max(0,ground-y);sx=round(x+.65*z);sy=round(ground+.325*z)
   if 0<=sx<out.width and 0<=sy<out.height:pix[sx,sy]=64
 out=out.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(.65));box=out.getbbox()
 if not box:return Image.new('L',(1,1)),0,0
 return out.crop(box).point(lambda a:((a+4)//8)*8),ax-box[0],ay-box[1]
