#!/usr/bin/env python3
"""Compile source RGBA atlases to bounded, row-cropped indexed PSP sprites.
Only resize, crop and quantize artwork; no runtime image decoder or files.
"""
from pathlib import Path
from PIL import Image, ImageOps
import json
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'src/art_data.h'
SPECS=[('buildings.png',[(116,110),(120,114),(142,136),(92,150),(116,112),(100,91),(108,104),(104,100)]),
       ('wilderness.png',[(68,86),(48,43),(58,104),(56,89),(38,32),(46,48),(56,51),(49,72)]),
       ('furniture.png',[(64,55),(86,58),(68,44),(64,87),(37,31),(52,74),(24,54),(74,40)])]
def arr(name,typ,vals):
 return 'static const '+typ+' '+name+'[] = {\n'+',\n'.join(','.join(map(str,vals[i:i+24])) for i in range(0,len(vals),24))+'\n};\n'
lines=['/* Generated by scripts/pack_art.py; do not edit. */\n#ifndef DUST_ART_DATA_H\n#define DUST_ART_DATA_H\n#include <stdint.h>\ntypedef struct {int w,h; const uint8_t *pixels; const uint16_t *rows; const uint32_t *palette;} ArtSprite;\n']
entries=[];stats=[];total=0
for filename,sizes in SPECS:
 source=Image.open(ROOT/'assets/art'/filename).convert('RGBA')
 cw,ch=source.width//4,source.height//2
 for i,(mw,mh) in enumerate(sizes):
  im=source.crop((i%4*cw,i//4*ch,(i%4+1)*cw,(i//4+1)*ch))
  alpha=im.getchannel('A').point(lambda a:255 if a>=220 else a if a>=32 else 0)
  im.putalpha(alpha);box=alpha.getbbox();im=im.crop(box)
  im.thumbnail((mw,mh),Image.Resampling.LANCZOS)
  # Quantize soft edge alpha separately; opaque interior has no blend overhead.
  al=im.getchannel('A').point(lambda a:255 if a>=220 else (a//64)*64 if a>=64 else 0)
  im.putalpha(al)
  im=im.quantize(colors=256,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
  pal=im.getpalette('RGBA');pal=pal+[0]*(1024-len(pal));palette=[pal[j]|pal[j+1]<<8|pal[j+2]<<16|pal[j+3]<<24 for j in range(0,1024,4)]
  raw=list(im.getdata());rows=[];data=[]
  for y in range(im.height):
   row=raw[y*im.width:(y+1)*im.width];vis=[x for x,p in enumerate(row) if palette[p]>>24]
   a,b=(min(vis),max(vis)+1) if vis else (0,0)
   rows.extend([len(data),a,b]);data.extend(row[a:b])
  name='art_'+str(len(entries))
  lines += [arr(name+'_data','uint8_t',data),arr(name+'_rows','uint16_t',rows),arr(name+'_palette','uint32_t',[hex(p)+'u' for p in palette])]
  entries.append('{%d,%d,%s_data,%s_rows,%s_palette}'%(im.width,im.height,name,name,name))
  size=len(data)+len(rows)*2+1024;total+=size
  stats.append(dict(source=filename,cell=i,width=im.width,height=im.height,bytes=size))
  im.convert('RGBA').save(ROOT/'assets/art'/f'sprite-{len(entries)-1:02d}.png')
lines+=['#define ART_COUNT '+str(len(entries))+'\nstatic const ArtSprite artSprites[ART_COUNT]={\n'+',\n'.join(entries)+'\n};\n#endif\n']
OUT.write_text(''.join(lines));(ROOT/'assets/art/budget.json').write_text(json.dumps(dict(rom_bytes=total,palette_cache_bytes=len(entries)*256*4,sprites=stats),indent=2)+'\n')
print('Packed',len(entries),'sprites;',total,'bytes ROM;',len(entries)*256*4,'bytes palette RAM')
