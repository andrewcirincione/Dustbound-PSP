#!/usr/bin/env python3
"""Compile 100 generated weapon drawings and calibrated handle pivots for PSP."""
from pathlib import Path
from PIL import Image
import json,sys,hashlib
ROOT=Path(__file__).resolve().parents[1];ART=ROOT/'assets/art/arsenal-expansion';PACKED=ART/'packed';PACKED.mkdir(exist_ok=True)
OUT=ROOT/'build/arsenal';OUT.mkdir(parents=True,exist_ok=True)
weapons=json.loads((ART/'weapons.json').read_text());assert len(weapons)==100
fits=json.loads((ART/'fits.json').read_text()) if (ART/'fits.json').exists() else {}
def arr(name,typ,values):return 'static const '+typ+' '+name+'[]={\n'+',\n'.join(','.join(map(str,values[i:i+24])) for i in range(0,len(values),24))+'\n};\n'
entries=[];anchors=[];code=['/* Generated by scripts/pack_arsenal.py from 100 independent drawings. */\n#ifndef DUST_ARSENAL_ART_DATA_H\n#define DUST_ARSENAL_ART_DATA_H\n#define ARSENAL_ART_FIRST (ARMOR_ART_FIRST+ARMOR_SETS*6)\n'];ready=[];budget=0
for w in weapons:
    raw=ART/w['source'];dest=PACKED/(w['slug']+'.png');key=str(w['index'])
    if raw.exists() and (not dest.exists() or raw.stat().st_mtime>dest.stat().st_mtime):
        im=Image.open(raw).convert('RGBA');alpha=im.getchannel('A').point(lambda a:255 if a>=160 else 0);box=alpha.getbbox();assert box,w['name']
        # Source canvas position is only a hint. The actual pivot must land
        # on an opaque handle texel, never on transparent atlas padding.
        hx,hy=w['grip_hint'];wanted_y=round(im.height*hy)
        wanted_y=max(box[1]+2,min(box[3]-3,wanted_y));ap=alpha.load()
        candidates=[]
        for y in range(max(box[1],wanted_y-im.height//12),min(box[3],wanted_y+im.height//12)):
            xs=[x for x in range(box[0],box[2]) if ap[x,y]]
            if xs:
                center=min(xs,key=lambda x:abs(x-im.width*hx));width=xs[-1]-xs[0]+1
                candidates.append((abs(y-wanted_y)+abs(center-im.width*hx)*.2+width*.02,center,y))
        assert candidates,w['name'];_,gx,gy=min(candidates)
        im.putalpha(alpha);im=im.crop(box);old=im.size;im.thumbnail((96,112),Image.Resampling.LANCZOS)
        sx,sy=im.width/old[0],im.height/old[1];gx=(gx-box[0])*sx;gy=(gy-box[1])*sy
        im.putalpha(im.getchannel('A').point(lambda a:255 if a>=160 else 0));im.save(dest)
        fits[key]={'grip':[gx,gy],'scale':w['height']/im.height,'edge':w['edge'],'source_sha256':hashlib.sha256(raw.read_bytes()).hexdigest(),'source_box':box,'packed':[im.width,im.height]}
    if not dest.exists():
        entries.append('{0}');anchors.append('{0}');continue
    im=Image.open(dest).convert('RGBA');assert key in fits
    z=fits[key];gx,gy=z['grip'];gx=max(0,min(im.width-1,gx));gy=max(0,min(im.height-1,gy));ap=im.getchannel('A')
    if ap.getpixel((round(gx),round(gy)))<128:
        opaque=[(abs(x-gx)+abs(y-gy),x,y) for y in range(im.height) for x in range(im.width) if ap.getpixel((x,y))>=128]
        _,gx,gy=min(opaque);fits[key]['grip']=[gx,gy]
    q=im.quantize(colors=64,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
    pal=q.getpalette('RGBA');pal += [0]*(1024-len(pal));palette=[pal[j]|pal[j+1]<<8|pal[j+2]<<16|pal[j+3]<<24 for j in range(0,1024,4)]
    pixels=list(q.get_flattened_data());data=[];rows=[]
    for y in range(im.height):
        row=pixels[y*im.width:(y+1)*im.width];vis=[x for x,p in enumerate(row) if palette[p]>>24]
        lo,hi=(min(vis),max(vis)+1) if vis else (0,0);rows.extend((len(data),lo,hi));data+=row[lo:hi]
    name='arsenal_'+key
    code += [arr(name+'_pixels','uint8_t',data),arr(name+'_rows','uint16_t',rows),arr(name+'_pal','uint32_t',[hex(p)+'u' for p in palette])]
    entries.append('{%d,%d,0,0,%s_pixels,%s_rows,%s_pal}'%(im.width,im.height,name,name,name));anchors.append('{%.5ff,%.5ff,%.6ff,%d}'%(gx,gy,z['scale'],z['edge']))
    budget+=len(data)+len(rows)*2+1024;ready.append(w['index'])
code+=['static const ArtSprite arsenalSprites[ARSENAL_WEAPONS]={\n'+',\n'.join(entries)+'\n};\nstatic const WeaponArt arsenalWeaponArt[ARSENAL_WEAPONS]={\n'+',\n'.join(anchors)+'\n};\n#define ARSENAL_READY '+str(len(ready))+'\n#endif\n']
(ROOT/'src/arsenal_art_data.h').write_text(''.join(code));(ART/'fits.json').write_text(json.dumps(fits,indent=2)+'\n')
meta=['/* Generated weapon catalog; item IDs append to the v30 catalog. */\n#ifndef DUST_ARSENAL_DATA_H\n#define DUST_ARSENAL_DATA_H\ntypedef struct {const char*name;int type,family,tier,faction,power,weight,penetration,accuracy,price;float range,cooldown;} ArsenalDef;\nstatic const ArsenalDef arsenalDefs[ARSENAL_WEAPONS]={\n']
for w in weapons:meta.append('{%s,%d,%d,%d,%s,%d,%d,%d,%d,%d,%.3ff,%.3ff},\n'%(json.dumps(w['name']),w['type'],w['family'],w['tier'],w['faction'],w['power'],w['weight'],w['penetration'],w['accuracy'],w['price'],w['range'],w['cooldown']))
meta+=['};\n#endif\n'];(ROOT/'src/arsenal_data.h').write_text(''.join(meta))
(ART/'generation-progress.json').write_text(json.dumps({'planned':100,'generated':ready,'packed_bytes':budget},indent=2)+'\n')
print('Packed',len(ready),'/100 independent weapon drawings;',budget,'bytes indexed art')
if len(ready)!=100 and '--allow-incomplete' not in sys.argv:raise SystemExit('Weapon generation is incomplete; do not publish.')
