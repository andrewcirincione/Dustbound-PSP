static uint32_t reviewPixels[480*272];
static void save_review_frame(const char *root,int n,const char *kind){
    char path[512];snprintf(path,sizeof(path),"%s/%02d-%s.ppm",root,n+1,kind);
    FILE *f=fopen(path,"wb");assert(f);fputs("P6\n480 272\n255\n",f);
    for(int i=0;i<480*272;i++){uint32_t c=reviewPixels[i];unsigned char p[]={c&255,c>>8&255,c>>16&255};fwrite(p,1,3,f);}fclose(f);
}
static void reset_art(void){
    memcpy(artSprites,baseArtSprites,sizeof(artSprites));
    memcpy(torsoFits,baseTorsoFits,sizeof(torsoFits));
    memset(paintPalettes,0,sizeof(paintPalettes));memset(paletteNext,0,sizeof(paletteNext));
    memset(actorCache,0,sizeof(actorCache));memset(artLight,0,sizeof(artLight));
}
static void install_preview(const RecoveredSet *s,Actor *a){
    const int slots[]={1,2,4,3};const char *parts[]={"body","headwear","legwear","boots"};
    static char names[4][64],description[112];
    snprintf(description,sizeof(description),"Recovered development preview. Arm %d; weight %d.",s->armor,s->weight);
    for(int j=0;j<4;j++){
        int family=s->family[j],id=gear_id(family,1,1),sprite=j==0?family:j==1?family:j==2?64+family-68:80+family-60;
        artSprites[sprite]=s->sprite[j];
        snprintf(names[j],sizeof(names[j]),"%s %s",s->name,parts[j]);
        itemDefs[id].name=names[j];itemDefs[id].desc=description;
        itemDefs[id].color=0x808080;itemDefs[id].quality=0;
        itemDefs[id].armor=j==0?s->armor:j==1?s->armor/2:s->armor/3;
        itemDefs[id].weight=j==0?s->weight:j==1?2:1;
        itemDefs[id].speed=j==0?s->speed:0;itemDefs[id].stealth=j==0?s->stealth:0;
        itemDefs[id].protection=j==0?s->weather:0;
        a->gear[slots[j]]=id;
    }
    torsoFits[s->family[0]-32]=s->fit;
}
